def glyph(ch: str) -> Tuple[int, ...]:
    c = ch.upper()
    if c in _FONT:
        return _FONT[c]
    if ch == " ":
        return _FONT[" "]
    return (0x1F,) * GLYPH_H  # fallback solid block


def draw_text(put, x: int, y: int, text: str, spacing: int = 1) -> int:
    """Draw ``text`` with the 5x7 font at integer offset ``(x, y)``.

    ``put(px, py)`` is called for every lit pixel of every glyph — the
    caller owns the surface, so this module stays free of any pixel
    storage.  Returns the number of pixels offered.
    """
    n = 0
    cx = x
    for ch in text:
        rows = glyph(ch)
        for row in range(GLYPH_H):
            bits = rows[row]
            for col in range(GLYPH_W):
                if bits & (0x10 >> col):
                    put(cx + col, y + row)
                    n += 1
        cx += GLYPH_W + spacing
    return n
